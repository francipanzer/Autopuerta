-- Albaranes de obra: administración crea y asigna; cada técnico solo ve
-- los documentos asignados a su ficha de empleado.
-- Ejecutar después de SUPABASE_AUTH_ROLES.sql y SUPABASE_PUSH.sql.
-- Para avisos push, desplegar también supabase/functions/send-push.

create table if not exists public.albaranes (
  id uuid primary key default gen_random_uuid(),
  numero bigint generated by default as identity unique,
  fecha date not null default current_date,
  clienteid text,
  clientenombre text not null,
  clientedireccion text not null default '',
  clientedocumento text not null default '',
  clientetelefono text not null default '',
  descripcion text not null default '',
  lineas jsonb not null default '[]'::jsonb,
  presupuestoid text,
  tecnicoids text[] not null default '{}'::text[],
  estado text not null default 'pendiente' check (estado in ('pendiente', 'firmado')),
  firmacliente text,
  firmadoat timestamptz,
  createdby uuid not null references auth.users(id),
  createdat timestamptz not null default now(),
  updatedat timestamptz not null default now()
);

alter table public.albaranes
  add column if not exists presupuestoid text;

create index if not exists idx_albaranes_fecha on public.albaranes(fecha desc);
create index if not exists idx_albaranes_tecnicos on public.albaranes using gin(tecnicoids);
create unique index if not exists idx_albaranes_presupuesto_unico
  on public.albaranes(presupuestoid)
  where presupuestoid is not null;

do $$
declare
  albaran_sequence text := pg_get_serial_sequence('public.albaranes', 'numero');
begin
  if albaran_sequence is not null then
    execute format('grant usage, select on sequence %s to authenticated', albaran_sequence);
  end if;
end $$;

alter table public.albaranes enable row level security;
revoke all on public.albaranes from anon;
grant select, insert, update, delete on public.albaranes to authenticated;

drop policy if exists "Admins manage albaranes" on public.albaranes;
create policy "Admins manage albaranes"
  on public.albaranes for all to authenticated
  using (public.app_is_admin())
  with check (public.app_is_admin());

drop policy if exists "Assigned technicians read albaranes" on public.albaranes;
create policy "Assigned technicians read albaranes"
  on public.albaranes for select to authenticated
  using (
    public.app_is_technician()
    and public.app_employee_id() = any(tecnicoids)
  );

create or replace function public.validate_albaran_presupuesto()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.presupuestoid is not null and not exists (
    select 1
    from public.presupuestos p
    where p.id::text = new.presupuestoid
      and lower(p.estado::text) = 'aprobado'
  ) then
    raise exception 'Solo se puede crear un albaran desde un presupuesto aprobado';
  end if;
  return new;
end;
$$;

drop trigger if exists validar_presupuesto_albaran on public.albaranes;
create trigger validar_presupuesto_albaran
  before insert or update of presupuestoid on public.albaranes
  for each row execute function public.validate_albaran_presupuesto();

create or replace function public.sign_albaran(p_id uuid, p_signature text)
returns void
language plpgsql security definer
set search_path = ''
as $$
begin
  if not public.app_is_active_user() then
    raise exception 'Authentication required';
  end if;
  if p_signature is null
    or p_signature not like 'data:image/png;base64,%'
    or length(p_signature) > 1000000 then
    raise exception 'Invalid signature';
  end if;
  if not exists (
    select 1
    from public.albaranes a
    where a.id = p_id
      and (
        public.app_is_admin()
        or (
          public.app_is_technician()
          and public.app_employee_id() = any(a.tecnicoids)
        )
      )
  ) then
    raise exception 'Albaran not found or not assigned to this user';
  end if;
  update public.albaranes
  set firmacliente = p_signature,
      firmadoat = now(),
      estado = 'firmado',
      updatedat = now()
  where id = p_id;
end;
$$;
revoke all on function public.sign_albaran(uuid, text) from public, anon;
grant execute on function public.sign_albaran(uuid, text) to authenticated;

create or replace function public.notify_albaran_asignado()
returns trigger
language plpgsql security definer
set search_path = ''
as $$
declare
  secret text;
  row_data jsonb := to_jsonb(new);
begin
  if tg_op = 'UPDATE' and old.tecnicoids is not distinct from new.tecnicoids then
    return new;
  end if;
  if coalesce(cardinality(new.tecnicoids), 0) = 0 then
    return new;
  end if;
  if to_regclass('public.push_config') is not null then
    execute 'select value from public.push_config where key = $1'
      into secret using 'webhook_secret';
  end if;
  if coalesce(secret, '') = '' then
    raise warning 'No se envio aviso push para el albaran %, falta push_config.webhook_secret', new.id;
    return new;
  end if;
  perform net.http_post(
    url := 'https://ziimllianelsocrdeeut.supabase.co/functions/v1/send-push',
    headers := jsonb_build_object('Content-Type', 'application/json', 'x-webhook-secret', secret),
    body := jsonb_build_object(
      'kind', 'albaran_asignado',
      'tecnicoids', to_jsonb(new.tecnicoids),
      'numero', 'ALB-' || to_char(new.fecha, 'YYYY') || '-' || lpad(new.numero::text, 4, '0'),
      'cliente', coalesce(row_data->>'clientenombre', '')
    )
  );
  return new;
exception when others then
  raise warning 'No se pudo enviar aviso push para el albaran %: %', new.id, sqlerrm;
  return new;
end;
$$;

drop trigger if exists push_albaran_asignado on public.albaranes;
create trigger push_albaran_asignado
  after insert or update of tecnicoids on public.albaranes
  for each row execute function public.notify_albaran_asignado();

